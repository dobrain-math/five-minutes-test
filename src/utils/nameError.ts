/**
 * 학생명 형식 검사. 완성된 한글 글자(가~힣)만 받는다 — 외국어·숫자·공백·특수문자·자음/모음 낱자는 막는다(2026-11-10).
 * 문구는 하나로 통일, 네 항목만(사용자 요청). 제목 줄 오른쪽에 한 줄로 들어가야 해서 짧게 —
 * 「올바른 이름 형식으로 입력해 주세요. (… 제외)」는 329px 라 360px 휴대폰에서 «학생명»과 겹쳤다.
 * 빈칸은 null(문구 없이 시작 버튼만 막는다).
 */
export function nameError(name: string): string | null {
	if (name === '' || /^[가-힣]+$/.test(name)) return null;
	return '외국어·숫자·공백·특수문자는 쓸 수 없습니다.';
}
