/**
 * 학생명 형식 검사. 완성된 한글 글자(가~힣)만 받는다 — 외국어·숫자·공백·특수문자·자음/모음 낱자는 막는다(2026-11-10).
 * 문구는 하나로 통일(사용자 요청 꼴 «유효한 이름 형식으로 … (… 제외)»). 빈칸은 null(문구 없이 시작 버튼만 막는다).
 * 줄바꿈(\n)은 제목 줄 오른쪽에 두 줄로 붙이기 위한 것(화면은 white-space: pre-line).
 */
export function nameError(name: string): string | null {
	if (name === '' || /^[가-힣]+$/.test(name)) return null;
	return '올바른 이름 형식으로 입력해 주세요.\n(외국어·숫자·공백·특수문자 제외)';
}
